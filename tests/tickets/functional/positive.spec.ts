/**
 * ============================================================================
 * COMPONENT: Tickets Feature
 * FOLDER:    playwright/tickets/functional/
 * MODULE:    positive.spec.ts
 * TAXONOMY:  1. Functional Testing › Happy Path & Core Workflows
 * ASSIGNED WORKER: Worker 3 (project: worker-3 | account: bot.worker3@quicktix.test)
 * WORKER BATCH:    Tickets Batch 1 of 2 (tickets/functional, tickets/resilience, tickets/api | ~195.1s total)
 * ============================================================================
 * WHAT THIS MODULE DOES:
 * Verifies core end-to-end user workflows for ticket lifecycle management:
 *   1. Create Ticket: Opens create modal via `ticket-new`, submits valid form,
 *      and asserts the new ticket appears in `ticket-list`.
 *   2. Edit Ticket: Opens edit modal via `ticket-edit` on seeded ticket,
 *      updates status to "Resolved", and asserts badge updates.
 *   3. Delete Ticket: Triggers deletion via `ticket-delete`, confirms in
 *      custom modal (`confirm-dialog`), and asserts row is removed from DOM.
 *   4. Native Select Status Filter: Selects "Open" via `status-filter`,
 *      asserting exactly 2 rows render.
 *   5. Segmented Status Tabs: Clicks "Resolved" tab, asserting only resolved tickets show.
 *   6. Quick Status Dropdown: Changes status directly on the ticket card via
 *      `ticket-quick-status` select element without opening modal.
 *   7. Live Keyword Search: Types search query into `ticket-search`, asserts
 *      filtered matching tickets, and verifies clear search restores all tickets.
 *
 * COMMUNICATES WITH:
 *   - Components: `TicketListComponent`, `TicketComponent`, `TicketFormComponent`, `ConfirmDialogComponent`
 *   - Backend Routes: `GET /api/tickets`, `POST /api/tickets`, `PUT /api/tickets/:id`, `DELETE /api/tickets/:id`
 *   - Fixtures: `base.fixture.ts` (auto-resets database before each test)
 *   - Mock Data: `SEEDED_TICKETS`
 * ============================================================================
 */

import { test, expect } from '../../fixtures/base.fixture.js';
import { SEEDED_TICKETS } from '../../fixtures/mock-data.js';

// [ASSIGNED WORKER: Worker 3] — Executed deterministically by Worker 3 (Tickets Batch 1 of 2 (tickets/functional, tickets/resilience, tickets/api | ~195.1s total))
test.describe('Tickets Feature › Functional › Positive Testing', () => {
  test.beforeEach(async ({ page }) => {
    // Navigate directly to the tickets dashboard (authenticated session is inherited)
    await page.goto('/tickets');
    await expect(page.getByTestId('ticket-list')).toBeVisible();
  });

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Create ticket and see in list',
    { tag: ['@smoke', '@tickets', '@positive'] },
    async ({ page }) => {
      const ticketTitle = `E2E Functional Ticket - ${Date.now()}`;
      const ticketDesc = 'Detailed description generated by Playwright automated test.';

      // Step 1: Click the "+ Create Ticket" action button
      await page.getByTestId('ticket-new').click();
      await expect(page.getByTestId('ticket-form')).toBeVisible();

      // Step 2: Fill out form inputs
      await page.getByTestId('ticket-title-input').fill(ticketTitle);
      await page.getByTestId('ticket-description-input').fill(ticketDesc);
      await page.getByTestId('ticket-priority-select').selectOption('High');

      // Step 3: Submit the ticket creation form
      await page.getByTestId('ticket-submit').click();

      // Step 4: Verify modal closes
      await expect(page.getByTestId('ticket-form')).toBeHidden();

      // Step 5: Assert the newly created ticket appears in the ticket list
      const newTicketCard = page.locator('[data-testid="ticket-row"]', { hasText: ticketTitle });
      await expect(newTicketCard).toBeVisible();
      await expect(newTicketCard.getByTestId('ticket-title')).toHaveText(ticketTitle);
      await expect(newTicketCard.getByTestId('ticket-status')).toHaveText('Open');
      await expect(newTicketCard).toContainText('High Priority');
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Edit seeded Open ticket to Resolved',
    { tag: ['@smoke', '@tickets', '@positive'] },
    async ({ page }) => {
      // Step 1: Locate seeded Ticket 1 ("Fix login button styling")
      const targetCard = page.locator(`[data-ticket-id="${SEEDED_TICKETS.ticket1.id}"]`);
      await expect(targetCard).toBeVisible();
      await expect(targetCard.getByTestId('ticket-status')).toHaveText('Open');

      // Step 2: Click the Edit button on Ticket 1
      await targetCard.getByTestId('ticket-edit').click();
      await expect(page.getByTestId('ticket-form')).toBeVisible();

      // Step 3: Change status to "Resolved" in the form and submit
      await page.getByTestId('ticket-status-select').selectOption('Resolved');
      await page.getByTestId('ticket-submit').click();

      // Step 4: Verify modal closes and status badge updates to "Resolved"
      await expect(page.getByTestId('ticket-form')).toBeHidden();
      await expect(targetCard.getByTestId('ticket-status')).toHaveText('Resolved');
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Delete ticket via confirm modal',
    { tag: ['@smoke', '@tickets', '@positive'] },
    async ({ page }) => {
      // Step 1: Locate seeded Ticket 4 ("Setup automated backups")
      const targetCard = page.locator(`[data-ticket-id="${SEEDED_TICKETS.ticket4.id}"]`);
      await expect(targetCard).toBeVisible();

      // Step 2: Click the Delete button to open the confirmation modal
      await targetCard.getByTestId('ticket-delete').click();
      const confirmModal = page.getByTestId('confirm-dialog');
      await expect(confirmModal).toBeVisible();
      await expect(confirmModal).toContainText('Setup automated backups');

      // Step 3: Confirm deletion
      await page.getByTestId('confirm-accept').click();

      // Step 4: Assert confirmation modal is dismissed and ticket row is removed
      await expect(confirmModal).toBeHidden();
      await expect(page.locator(`[data-ticket-id="${SEEDED_TICKETS.ticket4.id}"]`)).toHaveCount(0);
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Filter by Open shows exactly 2 rows using native status-filter select',
    { tag: ['@smoke', '@tickets', '@positive'] },
    async ({ page }) => {
      // Step 1: Assert all 4 seeded tickets initially visible
      await expect(page.getByTestId('ticket-row')).toHaveCount(4);

      // Step 2: Select "Open" in the native status-filter dropdown
      await page.getByTestId('status-filter').selectOption('Open');

      // Step 3: Assert exactly 2 rows render (owner scoping verified)
      const rows = page.getByTestId('ticket-row');
      await expect(rows).toHaveCount(2);

      // Verify each rendered ticket has "Open" status
      for (const row of await rows.all()) {
        await expect(row.getByTestId('ticket-status')).toHaveText('Open');
      }
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Filter tickets using segmented status tab buttons',
    { tag: ['@tickets', '@positive'] },
    async ({ page }) => {
      // Step 1: Click the "Resolved" status tab
      await page.locator('.filter-tabs .tab-btn', { hasText: 'Resolved' }).click();

      // Step 2: Assert only the single seeded resolved ticket is displayed
      const rows = page.getByTestId('ticket-row');
      await expect(rows).toHaveCount(1);
      await expect(rows.first().getByTestId('ticket-title')).toHaveText('Setup automated backups');

      // Step 3: Click "All" tab to restore full list
      await page.locator('.filter-tabs .tab-btn', { hasText: 'All' }).click();
      await expect(page.getByTestId('ticket-row')).toHaveCount(4);
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Quick status dropdown on ticket card updates status immediately',
    { tag: ['@tickets', '@positive'] },
    async ({ page }) => {
      const targetCard = page.locator(`[data-ticket-id="${SEEDED_TICKETS.ticket2.id}"]`);
      await expect(targetCard).toBeVisible();
      await expect(targetCard.getByTestId('ticket-status')).toHaveText('Open');

      // Select "Closed" from the card's quick status selector
      const quickSelect = targetCard.getByTestId('ticket-quick-status');
      await quickSelect.selectOption('Closed');

      // Assert status badge reactively updates to "Closed"
      await expect(targetCard.getByTestId('ticket-status')).toHaveText('Closed');
    }
  );

  // [Worker 3] Executed on preassigned Worker 3 (bot.worker3@quicktix.test)
  test(
    'Live search input filters tickets by keyword and clear search restores list',
    { tag: ['@tickets', '@positive'] },
    async ({ page }) => {
      const searchInput = page.getByTestId('ticket-search');
      await expect(searchInput).toBeVisible();

      // Search for "memory"
      await searchInput.fill('memory');

      // Assert only 1 matching ticket is displayed
      const matchingRows = page.getByTestId('ticket-row');
      await expect(matchingRows).toHaveCount(1);
      await expect(matchingRows.first().getByTestId('ticket-title')).toContainText('Investigate memory leak');

      // Clear search via clear button
      const clearBtn = page.locator('.search-clear-btn');
      await expect(clearBtn).toBeVisible();
      await clearBtn.click();

      // Assert full ticket list is restored
      await expect(page.getByTestId('ticket-row')).toHaveCount(4);
      await expect(searchInput).toHaveValue('');
    }
  );
});
